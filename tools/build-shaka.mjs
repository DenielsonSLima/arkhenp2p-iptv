import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';

const root=new URL('../',import.meta.url),source=new URL('node_modules/shaka-player/',root);
const metadata=JSON.parse(await readFile(new URL('package.json',source),'utf8'));
if(metadata.version!=='5.2.13')throw new Error('Revise a integração antes de atualizar a versão do Shaka.');
const script=await readFile(new URL('dist/shaka-player.compiled.js',source));
const integrity='sha384-'+createHash('sha384').update(script).digest('base64');
await mkdir(new URL('web/assets/vendor/',root),{recursive:true});
await writeFile(new URL('web/assets/vendor/shaka-player.compiled.js',root),script);
await writeFile(new URL('web/assets/vendor/SHAKA-LICENSE.txt',root),await readFile(new URL('LICENSE',source)));
await writeFile(new URL('web/player/motores/distribuicao.js',root),
  `// Generated by npm run build:shaka; official local distribution, no runtime CDN.\nexport const SHAKA_DISTRIBUTION=Object.freeze(${JSON.stringify({version:metadata.version,src:'/assets/vendor/shaka-player.compiled.js',integrity})});\n`);
console.log(`Shaka ${metadata.version}: distribuição local e licença preparadas.`);

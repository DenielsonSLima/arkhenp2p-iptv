import {build} from 'esbuild';
import {readFile,readdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=fileURLToPath(new URL('../',import.meta.url));
const result=await build({
  absWorkingDir:root,entryPoints:['web/cloud-runtime-entry.js'],
  outfile:'web/assets/vendor/cloud-client.js',bundle:true,minify:true,
  format:'esm',platform:'browser',target:'es2022',legalComments:'eof',
  metafile:true,logLevel:'info',
});

// Include the notices for the packages actually distributed in the bundle.
// Keep copyright/NOTICE files as well as LICENSE, including transitive packages.
const packages=new Set();
for(const input of Object.keys(result.metafile.inputs)){
  const relative=input.replaceAll('\\','/');
  if(!relative.startsWith('node_modules/'))continue;
  const parts=relative.slice('node_modules/'.length).split('/');
  packages.add(parts[0].startsWith('@')?parts.slice(0,2).join('/'):parts[0]);
}
const notices=['ARKHEN cloud client — third-party licenses and notices',
  'Generated by npm run build:cloud from the packages included in cloud-client.js.'];
for(const name of [...packages].sort()){
  const directory=path.join(root,'node_modules',name);
  const metadata=JSON.parse(await readFile(path.join(directory,'package.json'),'utf8'));
  const files=(await readdir(directory,{withFileTypes:true})).filter(entry=>entry.isFile()&&/^(license|licence|copying|copyright|notice)([._-].*)?$/i.test(entry.name)).map(entry=>entry.name).sort();
  if(!files.length)throw new Error(`Missing license notice for ${name}; do not distribute the bundle until it is included.`);
  notices.push(`\n${'='.repeat(72)}\n${metadata.name}@${metadata.version}`);
  for(const file of files)notices.push(`\n${file}\n${await readFile(path.join(directory,file),'utf8')}`);
}
await writeFile(path.join(root,'web/assets/vendor/CLOUD-LICENSES.txt'),notices.join('\n')+'\n');
console.log(`Included license notices for ${packages.size} bundled packages.`);
